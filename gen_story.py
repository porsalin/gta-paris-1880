import json, story_data as S
W=json.load(open('map/world.json'))['landmarks']
VT={'gig','brougham','phaeton','barouche','omnibus'}
def steps(rec):
  out=[]
  for tok in rec.split('|'):
    code,_,text=tok.partition('~'); a=code.split(); c=a[0]; text=text.strip()
    if c=='g': s=dict(t='goto',at=a[1])
    elif c=='gf': s=dict(t='goto',at=a[1],foot=True)
    elif c=='st': s=dict(t='steal',vtype=a[1],at=a[2])
    elif c=='d': s=dict(t='deliver',at=a[1],time=0)
    elif c=='df': s=dict(t='deliver',at=a[1],time=0,fragile=True)
    elif c=='k': s=dict(t='kill',at=a[1],n=int(a[2]),armed='a' in a[3:],boss='b' in a[3:])
    elif c=='c': s=dict(t='collect',at=a[1],n=int(a[2]))
    elif c=='cs': s=dict(t='collect',at=a[1],n=int(a[2]),stealth=True)
    elif c=='sw': s=dict(t='collect',at=a[1],n=1,stealth=True,swap=True)
    elif c=='e': s=dict(t='escort',at=a[1],to=a[2],real='r' in a[3:])
    elif c=='al': s=dict(t='survive',lvl=int(a[1]),time=int(a[2]),alarm=True)
    elif c=='lo': s=dict(t='survive',lvl=int(a[1]),lose=True,time=0)
    elif c=='r': s=dict(t='race',cps=a[1].split(','),time=int(a[2]))
    elif c=='h': s=dict(t='hold',at=a[1],time=int(a[2]),armed=True)
    elif c=='x': s=dict(t='destroy',at=a[1],n=int(a[2]))
    elif c=='xv': s=dict(t='destroy',at=a[1],n=int(a[2]),what='vehicle',vtype=a[3])
    elif c=='sm': s=dict(t='smash',at=a[1],n=int(a[2]))
    elif c=='f': s=dict(t='goto',at=a[1],fence=int(a[2]))
    else: raise Exception(c)
    for k in ('at','to'):
      if k in s: assert s[k] in W or s[k]=='salon', s[k]
    for q in s.get('cps',[]): assert q in W, q
    s['text']=text; out.append(s)
  return out
M=[]; n=0
for ci,act in enumerate(S.STORY):
  for j,(fac,title,en,brief,rec,loot) in enumerate(act):
    n+=1; st=steps(rec)
    heist=any(s.get('stealth') or s.get('fragile') or s.get('alarm') for s in st)
    m=dict(id=f'm{n}',n=n,fac=fac,chapter=ci,title=title,en=en,brief=brief,steps=st,reward=1500+n*350+(1500 if heist else 0),respect=6+ci*2,heist=heist)
    if loot: m['loot']=loot
    if j==0: m['card']=True
    M.append(m)
for k,(title,en,brief,rec) in enumerate(S.SIDE):
  n+=1; M.append(dict(id=f's{n}',n=n,fac='side',chapter=-1,title=title,en=en,brief=brief,steps=steps(rec),reward=2000+k*400,respect=0))
POIK=sorted(W)+['salon']
FAC={k:dict(v,pool=[]) for k,v in S.CONTACTS.items()}
CH=[dict(act=a,season=b,title=c,text=d) for a,b,c,d in S.CHAPTERS]
DR=[dict(name=a,role=b,real=c) for a,b,c in S.DRAMATIS]
open('missions.js','w').write('// generated by gen_story.py from story_data.py\nexport const FACTIONS='+json.dumps(FAC,ensure_ascii=False)+';\nexport const CHAPTERS='+json.dumps(CH,ensure_ascii=False)+';\nexport const DRAMATIS='+json.dumps(DR,ensure_ascii=False)+';\nexport const MISSIONS='+json.dumps(M,ensure_ascii=False)+';\n')
print(len(M),'missions;',sum(1 for m in M if m.get('heist')),'heists')
